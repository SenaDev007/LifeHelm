/// Indique si une saisie téléphonique (séparateurs retirés) est plausible :
/// chiffres uniquement, « + » facultatif en tête, 6 à 16 chiffres.
final RegExp _phoneShape = RegExp(r'^\+?\d{6,16}$');

/// Normalise une saisie téléphonique en format international « +229… ».
///
/// Tolère les habitudes de saisie les plus courantes, le champ affichant
/// déjà l'indicatif du pays sélectionné ([country.dial]) :
///  • numéro local seul : « 01 97 12 34 56 » (Bénin 10 chiffres, format
///    2024) ou « 97 12 34 56 » (8 chiffres, ancien format) ;
///  • indicatif déjà tapé malgré le sélecteur : « +229 01 97 12 34 56 »,
///    « 229 01 97 12 34 56 » ou « 00 229 … » → l'indicatif n'est pas doublé ;
///  • numéro complet d'un autre pays : « +33 6 12 34 56 78 » → conservé
///    tel quel (le « + » est respecté).
///
/// Retourne null si la saisie est vide. Les caractères superflus
/// (espaces, tirets, parenthèses, points) sont ignorés.
String? normalizePhoneInput(String input, CountryInfo country) {
  var raw = input.trim().replaceAll(RegExp(r'[\s\-().]'), '');
  if (raw.isEmpty) return null;
  final dialDigits = country.dial.replaceAll(RegExp(r'[^0-9]'), '');
  // Indicatif du pays sélectionné déjà tapé → retiré (le champ l'ajoute).
  if (raw.startsWith('+$dialDigits')) {
    raw = raw.substring(1 + dialDigits.length);
  } else if (raw.startsWith('00$dialDigits')) {
    raw = raw.substring(2 + dialDigits.length);
  } else if (raw.startsWith(dialDigits) &&
      raw.length >= dialDigits.length + 8) {
    raw = raw.substring(dialDigits.length);
  }
  if (raw.startsWith('00')) raw = raw.substring(2);
  // Autre pays au format international complet → respecté tel quel.
  if (raw.startsWith('+')) return raw;
  return '${country.dial}$raw';
}

/// Vérifie qu'une saisie téléphonique brute est exploitable (utilisé pour
/// la validation avant soumission). Retourne true si vide (facultatif).
bool isPlausiblePhoneInput(String input) {
  final raw = input.trim().replaceAll(RegExp(r'[\s\-().]'), '');
  return raw.isEmpty || _phoneShape.hasMatch(raw);
}

