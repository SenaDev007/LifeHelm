/// Taxonomie financière exhaustive LifeHelm — catégories & sous-catégories
/// pour les recettes, les dépenses et la planification budgétaire, plus les
/// référentiels métier : professions, pays & indicatifs téléphoniques,
/// questions de sécurité. Source unique partagée par l'onboarding, la saisie
/// d'opérations, les budgets, les prêts et les statistiques.
///
/// Les identifiants (`slug`) sont stables : ils servent de clé de dédoublonnage
/// lors de l'amorçage et des montées de version (ensureTaxonomy).

class TaxoNode {
  const TaxoNode(this.slug, this.name, this.colorHex, this.icon, this.subs);

  /// Identifiant stable (ex. « inc-salariaux »).
  final String slug;
  final String name;
  final String colorHex;
  final IconData icon;

  /// Sous-catégories (libellés affichés tels quels).
  final List<String> subs;
}

